-- LINEITEM: L_SHIPDATE <= date '1998-12-01' - interval 90 day
CREATE TABLE LINEITEM_shipcut_a_h1 AS
SELECT * FROM LINEITEM
WHERE L_SHIPDATE <= DATE '1998-12-01' - INTERVAL 90 DAY;
CREATE TABLE LINEITEM_shipcut_a_h2 AS
SELECT * FROM LINEITEM
WHERE NOT (L_SHIPDATE <= DATE '1998-12-01' - INTERVAL 90 DAY)
   OR L_SHIPDATE IS NULL;
